import os
import sqlite3
from pathlib import Path

from dotenv import load_dotenv

DB_PATH = Path(__file__).resolve().parent.parent / "chatbot.db"  # backend/chatbot.db
load_dotenv(DB_PATH.parent.parent / ".env")


# SQLite는 $1을 이름 있는 매개변수로 해석하므로 번호별 사전으로 값을 전달한다.
# SQL을 변환하지 않으면서 Python 3.14 이상에서도 같은 조회문을 사용할 수 있다.
class _SQLiteConnection(sqlite3.Connection):
    # 공통 SQL의 위치별 값을 SQLite의 이름별 바인딩으로 연결한다.
    def execute(self, sql, parameters=(), /):
        if "$1" in sql and isinstance(parameters, (tuple, list)):
            parameters = {str(index): value for index, value in enumerate(parameters, 1)}
        return super().execute(sql, parameters)


# DATABASE_URL이 있으면 PostgreSQL, 없으면 로컬 SQLite에 연결한다.
# 두 DB가 지원하는 $1, $2 매개변수를 사용하며, 값은 SQL 문자열과 분리해서 전달한다.
# 각 라우트가 commit과 close를 맡고, commit 없이 닫힌 연결의 변경은 취소된다.
def get_db():
    database_url = os.getenv("DATABASE_URL", "").strip()
    if database_url:
        if not database_url.startswith(("postgresql://", "postgres://")):
            raise ValueError("DATABASE_URL에는 postgresql://로 시작하는 Neon 연결 주소를 넣어주세요.")
        import psycopg
        from psycopg.rows import dict_row

        return psycopg.connect(
            database_url, row_factory=dict_row, cursor_factory=psycopg.RawCursor, connect_timeout=10,
        )
    if os.getenv("RENDER") == "true":
        raise RuntimeError("Render에서는 대화 기록 보존을 위해 DATABASE_URL을 설정해야 합니다.")
    conn = sqlite3.connect(DB_PATH, factory=_SQLiteConnection)
    conn.row_factory = sqlite3.Row
    return conn


# 서버 시작 시 필요한 테이블을 준비한다. 기존 상담 DB에는 누락된 구조만 추가한다.
def init_db():
    conn = get_db()
    try:
        _create_tables(conn)
        conn.commit()
    finally:
        conn.close()


# 테이블 구조는 공유하고, 자동 증가 ID와 날짜 타입만 DB별로 선택한다.
# 기존 로컬 DB에는 suggestions 열을 보완하며 상담 기록은 그대로 유지한다.
def _create_tables(conn):
    local = isinstance(conn, sqlite3.Connection)
    message_id = ("INTEGER PRIMARY KEY AUTOINCREMENT" if local
                  else "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    timestamp = "DATETIME" if local else "TIMESTAMPTZ"
    conn.execute(f"""
        CREATE TABLE IF NOT EXISTS sessions (
            id TEXT PRIMARY KEY,
            created_at {timestamp} DEFAULT CURRENT_TIMESTAMP
        )
    """)
    conn.execute(f"""
        CREATE TABLE IF NOT EXISTS messages (
            id {message_id},
            session_id TEXT NOT NULL REFERENCES sessions(id),
            turn INTEGER NOT NULL,
            role TEXT NOT NULL,
            content TEXT NOT NULL,
            request_id TEXT UNIQUE,
            suggestions TEXT,
            created_at {timestamp} DEFAULT CURRENT_TIMESTAMP
        )
    """)
    # 이전 버전 DB에 suggestions 컬럼이 없으면 추가한다
    if local:
        columns = [row["name"] for row in conn.execute("PRAGMA table_info(messages)")]
        if "suggestions" not in columns:
            conn.execute("ALTER TABLE messages ADD COLUMN suggestions TEXT")
    conn.execute(f"""
        CREATE TABLE IF NOT EXISTS session_state (
            session_id TEXT PRIMARY KEY REFERENCES sessions(id),
            state_json TEXT NOT NULL,
            next_item_id INTEGER NOT NULL,
            updated_at {timestamp} DEFAULT CURRENT_TIMESTAMP
        )
    """)
    conn.execute(f"""
        CREATE TABLE IF NOT EXISTS career_maps (
            session_id TEXT PRIMARY KEY REFERENCES sessions(id),
            map_json TEXT NOT NULL,
            based_on_message_id BIGINT NOT NULL,
            updated_at {timestamp} DEFAULT CURRENT_TIMESTAMP
        )
    """)
    conn.execute(f"""
        CREATE TABLE IF NOT EXISTS controller_events (
            session_id TEXT NOT NULL REFERENCES sessions(id),
            turn INTEGER NOT NULL,
            event_json TEXT NOT NULL,
            created_at {timestamp} DEFAULT CURRENT_TIMESTAMP,
            PRIMARY KEY (session_id, turn)
        )
    """)
